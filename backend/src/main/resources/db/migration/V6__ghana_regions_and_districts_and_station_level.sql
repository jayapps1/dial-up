CREATE TABLE region_ref (
    id UUID PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL UNIQUE,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE district_ref (
    id UUID PRIMARY KEY,
    region_id UUID NOT NULL,
    code VARCHAR(100) NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    assembly_type VARCHAR(50) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_district_region FOREIGN KEY (region_id) REFERENCES region_ref(id) ON DELETE CASCADE
);

ALTER TABLE station ADD COLUMN IF NOT EXISTS station_level VARCHAR(50) NOT NULL DEFAULT 'DISTRICT_STATION';
ALTER TABLE station ADD COLUMN IF NOT EXISTS region_id UUID;
ALTER TABLE station ADD COLUMN IF NOT EXISTS district_id UUID;

CREATE INDEX idx_district_region ON district_ref(region_id);
CREATE INDEX idx_district_name ON district_ref(name);
CREATE INDEX idx_station_level ON station(station_level);

